import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { createTestApp } from '../helpers/app';
import { buildOpenApiDocument } from '../../src/docs/openapi';

/**
 * Every endpoint in the spec (§7 tables) is either implemented or explicitly deferred to a later
 * milestone. A Phase 1 endpoint can't silently go missing, and the coverage list for the mobile team
 * (`docs/API_COVERAGE.md`) is regenerated from the same data: `UPDATE_API_COVERAGE=1 npm test -- api-coverage`.
 */

createTestApp(); // registers every route

/** Spec endpoints that belong to later milestones (docs/BUILD_PLAN.md). First match wins. */
const DEFERRED: Array<[RegExp, string]> = [
  [
    /^\w+ \/org\b|^\w+ \/subscription-plans|^\w+ \/admin\/(organizations|subscription-plans)/,
    'M3 — Organizations',
  ],
  [/^\w+ \/admin\/analytics|^POST \/admin\/notifications\/broadcast/, 'M3.5 — Advanced admin'],
];

/** Milestones put on hold (docs/BUILD_PLAN.md) whose spec surface is fields and enums, not endpoints. */
const DEFERRED_MILESTONES = [
  {
    milestone: 'M2.6 — Video consultations',
    covers:
      'Bookings with `type = video` (refused while `features.video_consult` is off, the default); the `video` block on booking details (always `null`); the `video_consultation` category and its services (hidden from lookups, search and booking while the flag is off).',
  },
];

type SpecEndpoint = { section: string; method: string; path: string; description: string };

const specEndpoints = (): SpecEndpoint[] => {
  const spec = fs.readFileSync(path.resolve(__dirname, '../../docs/Reaya_Backend_Spec.md'), 'utf8');
  const rows: SpecEndpoint[] = [];
  let section = '';
  for (const line of spec.split('\n')) {
    const heading = /^#{2,4} (.*)/.exec(line);
    if (heading) section = heading[1].trim();
    const row = /^\|\s*`([A-Z/]+)`\s*\|\s*`([^`]+)`\s*\|\s*(.*?)\s*\|?\s*$/.exec(line);
    if (!row) continue;
    for (const method of row[1].split('/')) {
      rows.push({
        section,
        method,
        path: row[2].split('?')[0],
        description: row[3].replace(/\s*\|\s*$/, ''),
      });
    }
  }
  return rows;
};

const normalize = (method: string, p: string) => `${method.toUpperCase()} ${p.replace(/\{[^}]+\}/g, '{}')}`;

describe('API coverage against the spec', () => {
  const implemented = new Set<string>();
  const doc = buildOpenApiDocument();
  for (const [p, ops] of Object.entries(doc.paths ?? {})) {
    for (const method of Object.keys(ops as object))
      implemented.add(normalize(method, p.replace('/api/v1', '')));
  }
  const endpoints = specEndpoints().map((e) => {
    const id = normalize(e.method, e.path);
    const deferredTo = DEFERRED.find(([pattern]) => pattern.test(id))?.[1];
    return { ...e, id, done: implemented.has(id), deferredTo };
  });

  it('every spec endpoint is implemented or deferred to a named milestone', () => {
    expect(endpoints.length).toBeGreaterThan(200);
    expect(endpoints.filter((e) => !e.done && !e.deferredTo).map((e) => e.id)).toEqual([]);
  });

  it('deferred patterns only cover endpoints that are really missing', () => {
    expect(endpoints.filter((e) => e.done && e.deferredTo).map((e) => e.id)).toEqual([]);
  });

  it('docs/API_COVERAGE.md is up to date', () => {
    const lines = [
      '# API coverage',
      '',
      '<!-- Generated by tests/integration/api-coverage.test.ts — run `UPDATE_API_COVERAGE=1 npm test -- api-coverage`. -->',
      '',
      'Spec §7 endpoints and their status. Live request/response shapes: `docs/openapi.json` (Swagger UI at `/docs` outside production).',
      '',
      `**Implemented:** ${endpoints.filter((e) => e.done).length} · **Deferred:** ${endpoints.filter((e) => !e.done).length} (each to a named Phase 2 / 3 milestone)`,
    ];
    let section = '';
    for (const e of endpoints) {
      if (e.section !== section) {
        section = e.section;
        lines.push('', `## ${section}`, '', '| Method | Path | Status |', '|---|---|---|');
      }
      lines.push(`| \`${e.method}\` | \`${e.path}\` | ${e.done ? '✅ Built' : `⏳ ${e.deferredTo}`} |`);
    }
    lines.push(
      '',
      '## Deferred milestones (no endpoints of their own)',
      '',
      '| Milestone | Status | What waits for it |',
      '|---|---|---|',
      ...DEFERRED_MILESTONES.map((m) => `| ${m.milestone} | ⏸ Deferred — not cancelled | ${m.covers} |`),
    );
    const content = `${lines.join('\n')}\n`;
    const file = path.resolve(__dirname, '../../docs/API_COVERAGE.md');
    if (process.env.UPDATE_API_COVERAGE) fs.writeFileSync(file, content);
    expect(fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '').toBe(content);
  });
});
